def sign_message(priv: PrivKey, message: Buffer) -> Signature:
    """Signs a message using ECDSA with sha256 as the hash function"""
    z = sha256(message)
    while True:
        k = secrets.randbelow(N - 1) + 1
        # R = (x1, y1) = kG
        R = scalar_mult(k, (Gx, Gy))
        assert R
        # r = x1 mod n
        r = R[0] % N

        # retry if r = 0
        if r == 0:
            continue

        # k^(-1)
        k_inv = inv_mod(k, N)

        # s = 1/k * (H(M) + r * a) (mod n)
        s = (k_inv * (z + r * priv)) % N

        # retry if s = 0
        if s == 0:
            continue

        # return the signature (r, s)
        return (r, s)


# WARN: not used
def verify_signature(pub: PubKey, message: Buffer, signature: Signature) -> bool:
    """Check the ECDSA signature"""
    if pub is None or not is_on_curve(pub):
        return False
    r, s = signature
    # r and s are expected to be in NN^* and mod n
    if not (1 <= r < N and 1 <= s < N):
        return False
    # compute z = H(M)
    z = sha256(message)
    # s^(-1) mod n
    s_inv = inv_mod(s, N)
    # u1 = H(M)/s (mod n)
    u1 = (z * s_inv) % N
    # u2 = r/s (mod n)
    u2 = (r * s_inv) % N
    P1 = scalar_mult(u1, (Gx, Gy))
    P2 = scalar_mult(u2, pub)
    # P = (x1, y1) = u1G + u2A
    P = point_add(P1, P2)
    if P is None:
        return False
    # check if r = x1 mod n
    return (P[0] % N) == r


def forge_signature_for_infinity_pub(message: Buffer) -> Point:
    """Generate a valid signature when public key is None"""
    z = sha256(message)
    s = 1
    s_inv = inv_mod(s, N)
    u1 = (z * s_inv) % N
    point = scalar_mult(u1, (Gx, Gy))
    assert point is not None
    return (point[0] % N, s)


