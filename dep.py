# Elliptic curve computations (generated by ChatGPT)
def inv_mod(k: int, p: int) -> int:
    """calculates the inverse of k modulo p"""
    # TODO: Check if mathematically correct
    if k == 0:
        raise ZeroDivisionError("division by zero")
    if k < 0:
        return p - inv_mod(-k, p)
    s, old_s = 0, 1
    r, old_r = p, k
    while r != 0:
        q = old_r // r
        old_r, r = r, old_r - q * r
        old_s, s = s, old_s - q * s
    return old_s % p


# INFO: valid
def is_on_curve(point: Point | None):
    """Check if a point is on the Elliptic curve"""
    if point is None:
        return True
    x, y = point
    # Weistrass curve y^2 = x^3 + ax + b
    # NOTE: This is mathematically sound
    return (y * y - (x * x * x + A * x + B)) % P == 0


def point_add(p1: Point | None, p2: Point | None):
    """Adds two points on the elliptic curve"""
    # TODO: Check if mathematically correct
    if p1 is None:
        return p2
    if p2 is None:
        return p1
    x1, y1 = p1
    x2, y2 = p2
    if x1 == x2 and y1 != y2:
        return None
    if p1 == p2:
        m = (3 * x1 * x1 + A) * inv_mod(2 * y1, P) % P
    else:
        m = (y2 - y1) * inv_mod(x2 - x1, P) % P
    x3 = (m * m - x1 - x2) % P
    y3 = (m * (x1 - x3) - y1) % P
    return (x3, y3)


# INFO: mathematically sound, None means point to infinity
def scalar_mult(k: int, point: Point | None) -> Point | None:
    """Multiply a point on the curve by the scalar value k"""
    # Check that the point is on the curve otherwise the multiplication isn't
    # possible.
    assert is_on_curve(point)
    if k % N == 0 or point is None:
        # If k is perfectly divisible by N or now point was given, the result is None.
        # NOTE: If k is perfectly divisible by N, the result will be a None,
        # this check saves time
        return None
    if k < 0:
        # If k is negative, we simply multiply both inputs by -1 which is
        # simple to do and allows the next part of the algorithm to work.
        return scalar_mult(-k, (point[0], (-point[1]) % P))
    result = None
    addend = point
    # To calculate the result, we add point k times, effectively multiplying
    # the point by k
    while k:
        if k & 1:
            result = point_add(result, addend)
        addend = point_add(addend, addend)
        k >>= 1
    return result


